UPDATE S
SET S.IDCUSTOMERINVOICE= CASE 
								WHEN C.IDGROUP=3 AND C.IDSUPPLIER=4069 AND C.VVATINVOICE<>'J100000001' THEN 4069
								WHEN C.IDGROUP=3 AND C.IDSUPPLIER=4076 AND C.VVATINVOICE<>'J100000002' THEN 4076
						       ELSE S.IDDEALER
							END
FROM SALEORDER S 
INNER JOIN V_DEALERS C ON S.IDDEALER=C.IDDEALER

