	CREATE VIEW DBO.V_INVENTORYCOUNT_RESULTFIGO
	AS

	WITH TFI AS (
				SELECT T.IDSUPPLIER,I.IDINVENTORY,
				I.IDLOCATION,I.IDPART,I.IQUANTITY_NEW,I.IDCOUNT,
				ROW_NUMBER() OVER ( PARTITION BY T.IDSUPPLIER,I.IDINVENTORY,I.IDLOCATION,I.IDPART ORDER BY I.IDLOCATION,I.IDPART, I.IDCOUNT DESC) LASTIDCOUNT
				FROM INVENTORYCOUNTDETAIL I WITH (NOLOCK)
				INNER JOIN INVENTORYCOUNT T WITH (NOLOCK) ON T.ID=I.IDINVENTORY
				WHERE T.IDCOUNTTYPE=2
				AND I.IQUANTITY_NEW>0
				AND I.IDSTATUS=18
				)
	SELECT TFI.IDPART,P.VINNERCODE,P.VDESCRIPTION,SUM(TFI.IQUANTITY_NEW) AS ISTOCK
	FROM TFI
	INNER JOIN PART P WITH (NOLOCK) ON P.ID=TFI.IDPART
	WHERE TFI.LASTIDCOUNT=1
	GROUP BY TFI.IDPART,P.VINNERCODE,P.VDESCRIPTION