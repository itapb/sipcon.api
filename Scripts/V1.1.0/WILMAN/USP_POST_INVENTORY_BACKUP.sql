-- USP_POST_INVENTORY_BACKUP 5
CREATE PROCEDURE [dbo].[USP_POST_INVENTORY_BACKUP]
 @IDINVENTORY INT
AS
/* '===============================================================          
  '   NOMBRE                : 
  '   FECHA CREACIÓN        : 
  '   CREADO POR            : WILMAN CAMACHO
  '   CREADO PARA           :  
  '   FUNCIÓN               :  
  '   VERSIÓN               : 
  '   MODIFICADO EN         : 
  '   MODIFICADO POR        :  
  '   RAZÓN DE MODIFICACIÓN : 
  '===============================================================*/

SET XACT_ABORT ON               
SET NOCOUNT ON
SET LOCK_TIMEOUT 180000

BEGIN
BEGIN TRY
	BEGIN TRAN 
	
		DECLARE @IBACKUP INT
		DECLARE @HOY DATETIME
		DECLARE @IDSUPPLIER INT

		SELECT @IDSUPPLIER=IDSUPPLIER FROM INVENTORYCOUNT WITH (NOLOCK) WHERE ID=@IDINVENTORY

		SELECT @IBACKUP=MAX(IBACKUP) 
		FROM INVENTORYBACKUP WITH (NOLOCK)
		WHERE IDINVENTORY=@IDINVENTORY

		SELECT @IBACKUP=ISNULL(@IBACKUP,0)+1
		SELECT @HOY=GETDATE()

		INSERT INTO INVENTORYBACKUP(IDINVENTORY,IDLOCATION,IDPART,ISTOCK,IBACKUP,DCREATED)
		SELECT @IDINVENTORY,I.IDLOCATION,I.IDPART,I.ISTOCK,@IBACKUP,@HOY
		FROM INVENTORY I WITH (NOLOCK)
		INNER JOIN PART P WITH (NOLOCK) ON P.ID=I.IDPART
		WHERE P.IDSUPPLIER=@IDSUPPLIER
		AND I.ISTOCK>0


 	COMMIT TRAN
END TRY
BEGIN CATCH
	IF XACT_STATE() <> 0
			ROLLBACK TRAN
	DECLARE @ErrorMessage NVARCHAR(4000) 
	SELECT  @ErrorMessage = ERROR_PROCEDURE() + ' : ' + ERROR_MESSAGE()
	RAISERROR ( @ErrorMessage , 16,1) 
END CATCH

END
